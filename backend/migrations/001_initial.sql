CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE user_role AS ENUM ('customer', 'staff', 'admin');
CREATE TYPE reservation_status AS ENUM ('pending', 'confirmed', 'cancelled', 'completed');
CREATE TYPE email_status AS ENUM ('pending', 'sending', 'sent', 'failed');

CREATE TABLE provinces (
  id smallint PRIMARY KEY CHECK (id BETWEEN 1 AND 99),
  name varchar(80) NOT NULL UNIQUE
);

CREATE TABLE towns (
  id varchar(12) PRIMARY KEY,
  province_id smallint NOT NULL REFERENCES provinces(id) ON DELETE RESTRICT,
  name varchar(120) NOT NULL,
  ine_code varchar(12),
  latitude numeric(10, 7),
  longitude numeric(10, 7)
);
CREATE INDEX towns_name_idx ON towns (lower(name));

CREATE TABLE postal_codes (
  postal_code char(5) NOT NULL CHECK (postal_code ~ '^[0-9]{5}$'),
  town_id varchar(12) NOT NULL REFERENCES towns(id) ON DELETE CASCADE,
  PRIMARY KEY (postal_code, town_id)
);

CREATE TABLE persons (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  national_id varchar(16) NOT NULL UNIQUE,
  email varchar(254) NOT NULL CHECK (email = lower(email)),
  first_name varchar(80) NOT NULL,
  last_name_1 varchar(80) NOT NULL,
  last_name_2 varchar(80),
  gender varchar(32),
  street varchar(120),
  street_number varchar(16),
  postal_code char(5),
  role user_role NOT NULL DEFAULT 'customer',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT persons_email_unique UNIQUE (email)
);

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  person_id uuid NOT NULL UNIQUE REFERENCES persons(id) ON DELETE CASCADE,
  password_hash text,
  role user_role NOT NULL DEFAULT 'customer',
  email_verified_at timestamptz,
  password_reset_required boolean NOT NULL DEFAULT false,
  disabled_at timestamptz,
  failed_login_attempts smallint NOT NULL DEFAULT 0,
  locked_until timestamptz,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (password_hash IS NOT NULL OR password_reset_required)
);

CREATE TABLE email_verification_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE refresh_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  user_agent_hash char(64),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  replaced_by uuid REFERENCES refresh_sessions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refresh_sessions_user_idx ON refresh_sessions(user_id);

CREATE TABLE rooms (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  description text NOT NULL DEFAULT '',
  price_per_night numeric(10, 2) NOT NULL CHECK (price_per_night >= 0),
  area_m2 integer NOT NULL CHECK (area_m2 > 0),
  max_guests integer NOT NULL CHECK (max_guests > 0 AND max_guests <= 20),
  image_url text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE reservations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id integer NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
  person_id uuid NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
  check_in date NOT NULL,
  check_out date NOT NULL,
  guests integer NOT NULL CHECK (guests > 0),
  status reservation_status NOT NULL DEFAULT 'pending',
  total_price numeric(10, 2) NOT NULL CHECK (total_price >= 0),
  notes varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (check_out > check_in)
);
ALTER TABLE reservations
  ADD CONSTRAINT reservations_no_overlap
  EXCLUDE USING gist (
    room_id WITH =,
    daterange(check_in, check_out, '[)') WITH &&
  ) WHERE (status IN ('pending', 'confirmed'));
CREATE INDEX reservations_person_idx ON reservations(person_id, check_in DESC);
CREATE INDEX reservations_dates_idx ON reservations(check_in, check_out);

CREATE TABLE room_services (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(80) NOT NULL UNIQUE,
  price numeric(10, 2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE room_service_assignments (
  room_id integer NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
  service_id integer NOT NULL REFERENCES room_services(id) ON DELETE CASCADE,
  PRIMARY KEY (room_id, service_id)
);

CREATE TABLE activities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitor_person_id uuid REFERENCES persons(id) ON DELETE SET NULL,
  price_per_person numeric(10, 2) NOT NULL CHECK (price_per_person >= 0),
  description text NOT NULL,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE activity_schedules (
  activity_id integer NOT NULL REFERENCES activities(id) ON DELETE CASCADE,
  starts_at timestamptz NOT NULL,
  capacity integer CHECK (capacity > 0),
  PRIMARY KEY (activity_id, starts_at)
);

CREATE TABLE activity_participations (
  activity_id integer NOT NULL,
  starts_at timestamptz NOT NULL,
  person_id uuid NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
  PRIMARY KEY (activity_id, starts_at, person_id),
  FOREIGN KEY (activity_id, starts_at)
    REFERENCES activity_schedules(activity_id, starts_at) ON DELETE CASCADE
);

CREATE TABLE avatars (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  person_id uuid NOT NULL UNIQUE REFERENCES persons(id) ON DELETE CASCADE,
  storage_key uuid NOT NULL UNIQUE,
  content_type varchar(32) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 5242880),
  sha256 char(64) NOT NULL,
  original_name varchar(255),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE email_outbox (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  template varchar(60) NOT NULL,
  recipient varchar(254) NOT NULL,
  payload jsonb NOT NULL,
  status email_status NOT NULL DEFAULT 'pending',
  attempts smallint NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  last_error varchar(500),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX email_outbox_pending_idx ON email_outbox(next_attempt_at)
  WHERE status IN ('pending', 'failed');

CREATE TABLE audit_log (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
  action varchar(100) NOT NULL,
  target_type varchar(80),
  target_id varchar(100),
  ip_hash char(64),
  user_agent_hash char(64),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_created_idx ON audit_log(created_at DESC);
CREATE INDEX audit_log_actor_idx ON audit_log(actor_user_id, created_at DESC);

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER persons_updated_at BEFORE UPDATE ON persons
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER rooms_updated_at BEFORE UPDATE ON rooms
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER reservations_updated_at BEFORE UPDATE ON reservations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

